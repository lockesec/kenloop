"""One ledger helper, declared ledgers: damage is reported or refused, never
skipped; appends refuse past damage; strict ledgers refuse to be read in part; the declarations
write .gitattributes and the docs name every ledger."""
import json
from pathlib import Path

import pytest

from kenloop import loop
from kenloop.core import ledger as LG
from kenloop.core.errors import NotEvaluable

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "kenloop"


def _check(r):
    if "x" not in r:
        raise ValueError("needs x")


def test_read_reports_each_bad_line_and_keeps_the_rest(tmp_path):
    p = tmp_path / "log.jsonl"
    p.write_bytes(b'{"x": 1}\n{oops\n{"y": 2}\n\xff\xfe\n{"x": 3}\n')
    rows, problems = LG.read(p, _check)
    assert [r["x"] for r in rows] == [1, 3] and len(problems) == 3
    assert any("line 2" in q for q in problems) and any("not UTF-8" in q for q in problems)


def test_append_refuses_past_damage_and_checks_the_row(tmp_path):
    p = tmp_path / "recall.jsonl"
    LG.append(p, {"x": 1}, _check)
    with pytest.raises(ValueError):
        LG.append(p, {"y": 1}, _check)
    p.write_text(p.read_text() + "{broken\n")
    with pytest.raises(NotEvaluable, match="nothing appended"):
        LG.append(p, {"x": 2}, _check)
    assert p.read_text().count("\n") == 2


def test_a_strict_ledger_cannot_be_read_in_part(tmp_path):
    p = tmp_path / "renames.jsonl"
    p.write_text('{"from": "a", "to": "b"}\n{bad\n')
    with pytest.raises(NotEvaluable, match="cannot be read in part"):
        LG.read(p)


def test_no_code_appends_to_a_file_except_the_ledger_helper():
    hits = [str(f.relative_to(SRC)) for f in SRC.rglob("*.py") if f.name != "ledger.py"
            and ('open(' in (t := f.read_text(encoding="utf-8"))) and any(m in t for m in ('"a")', "'a')", '"a", '))]
    assert hits == []


def test_every_jsonl_the_code_names_is_declared():
    named = set()
    for f in SRC.rglob("*.py"):
        named |= set(__import__("re").findall(r"\b([a-z_]+\.jsonl)\b", f.read_text(encoding="utf-8")))
    assert named <= {d.file for d in LG.LEDGERS}, named - {d.file for d in LG.LEDGERS}


def test_gitattributes_comes_from_the_declarations_and_doctor_flags_a_gap(home, capsys):
    text = (home / ".gitattributes").read_text()
    assert text == LG.gitattributes() and "topics/*/promotions.jsonl merge=union" in text
    (home / ".gitattributes").write_text("topics/*/log.jsonl merge=union\n")
    from kenloop.career import config as CC
    capsys.readouterr()
    loop.doctor(CC.load(home))
    assert f"lacks {len(LG.LEDGERS) - 1} ledger line(s)" in capsys.readouterr().out


def test_the_docs_name_every_declared_ledger():
    docs = (ROOT / "docs" / "commands.md").read_text(encoding="utf-8")
    assert [d.file for d in LG.LEDGERS if d.file not in docs] == []


def test_doctor_fix_adds_only_the_missing_ledger_lines(home, capsys):
    """A new ledger made a real home's doctor say FINDINGS until the file was
    regenerated by hand."""
    from kenloop.career import config as CC
    (home / ".gitattributes").write_text("*.png binary\ntopics/*/log.jsonl merge=union\n")
    loop.doctor(CC.load(home), fix=True)
    text = (home / ".gitattributes").read_text()
    assert text.startswith("*.png binary\n") and all(ln in text.splitlines() for ln in LG.gitattributes().splitlines())
    capsys.readouterr()
    loop.doctor(CC.load(home))
    assert ".gitattributes lacks" not in capsys.readouterr().out
